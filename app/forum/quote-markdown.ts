/**
 * An attributed quote is ordinary Markdown: a source link, an empty quote line,
 * and source lines prefixed by a blockquote marker. The quote remains editable
 * in either editor and still parses as a normal blockquote for mention exclusion.
 */
const QUOTE_SOURCE_PREFIX = "↳ ";

function escapeLinkLabel(value: string): string {
  const delimiters = "\\*_{}[]<>!" + String.fromCharCode(96);
  return [...value.replace(/[\r\n]+/gu, " ")]
    .map((character) => delimiters.includes(character) ? "\\" + character : character)
    .join("");
}

export function attributedQuoteMarkdown({
  author,
  messageNumber,
  permalink,
  content,
}: {
  author: string;
  messageNumber: number;
  permalink: string;
  content: string;
}): string {
  const title = "[" + QUOTE_SOURCE_PREFIX + escapeLinkLabel(author) + " · #" + messageNumber + "](" + permalink + ")";
  const quoteLines = content.replace(/\r\n?|\n/gu, "\n")
    .split("\n")
    .map((line) => line ? "> " + line : ">")
    .join("\n");
  return "> " + title + "\n>\n" + quoteLines + "\n\n";
}

/** Identify only the attributed-quote header shape generated by the forum. */
/** React Markdown gives blockquote renderers HAST, not the source mdast nodes. */
export function isAttributedQuoteHeader(value: unknown): boolean {
  const node = value as { type?: string; tagName?: string; children?: unknown[] } | undefined;
  if (node?.type !== "element" || node.tagName !== "p"
    || !Array.isArray(node.children) || node.children.length !== 1) return false;
  const anchor = node.children[0] as {
    type?: string; tagName?: string; properties?: { href?: unknown }; children?: unknown[];
  } | undefined;
  if (anchor?.type !== "element" || anchor.tagName !== "a"
    || typeof anchor.properties?.href !== "string") return false;
  const label = anchor.children?.map((child) => {
    const text = child as { type?: string; value?: unknown } | undefined;
    return text?.type === "text" && typeof text.value === "string" ? text.value : "";
  }).join("") ?? "";
  return label.startsWith(QUOTE_SOURCE_PREFIX)
    && /\/topics\/[^?#]+#post-[^?#]+$/u.test(anchor.properties.href);
}
