/**
 * An attributed quote is ordinary Markdown: a source link, an empty quote line,
 * and source lines prefixed by a blockquote marker. The quote remains editable
 * in either editor and still parses as a normal blockquote for mention exclusion.
 */
const QUOTE_SOURCE_PREFIX = "↳ ";

function escapeLinkLabel(value: string): string {
  const delimiters = "\\*_{}[]<>!" + String.fromCharCode(96);
  return [...value.replace(/[\r\n]+/gu, " ").replace(/&/gu, "&amp;")]
    .map((character) => delimiters.includes(character) ? "\\" + character : character)
    .join("");
}

export function attributedQuoteMarkdown({
  author,
  messageNumber,
  permalink,
  content,
}: {
  author: string;
  messageNumber: number;
  permalink: string;
  content: string;
}): string {
  const title = "[" + QUOTE_SOURCE_PREFIX + escapeLinkLabel(author) + " · #" + messageNumber + "](" + permalink + ")";
  const quoteLines = content.replace(/\r\n?|\n/gu, "\n")
    .split("\n")
    .map((line) => line ? "> " + line : ">")
    .join("\n");
  return "> " + title + "\n>\n" + quoteLines + "\n\n";
}

/** Recognize only the exact attributed Markdown link shape generated by the forum. */
const ATTRIBUTED_LABEL = /^↳ .+ · #\d+$/u;
const POST_PERMALINK = /\/topics\/[^?#]+#post-[^?#]+$/u;

interface QuoteNode {
  type?: unknown;
  tagName?: unknown;
  value?: unknown;
  url?: unknown;
  properties?: { href?: unknown };
  children?: unknown[];
}

function asNode(value: unknown): QuoteNode | null {
  return value && typeof value === "object" ? value as QuoteNode : null;
}

function isSourceLink(label: string, permalink: string): boolean {
  return ATTRIBUTED_LABEL.test(label) && POST_PERMALINK.test(permalink);
}

/** ReactMarkdown blockquote renderers receive HAST with incidental whitespace children. */
export function isAttributedQuoteHeader(value: unknown): boolean {
  const blockquote = asNode(value);
  if (blockquote?.type !== "element" || blockquote.tagName !== "blockquote") return false;
  const first = blockquote.children?.find((child) => {
    const node = asNode(child);
    return !(node?.type === "text" && typeof node.value === "string" && !node.value.trim());
  });
  const paragraph = asNode(first);
  if (paragraph?.type !== "element" || paragraph.tagName !== "p"
    || paragraph.children?.length !== 1) return false;
  const link = asNode(paragraph.children[0]);
  if (link?.type !== "element" || link.tagName !== "a"
    || typeof link.properties?.href !== "string" || link.children?.length !== 1) return false;
  const label = asNode(link.children[0]);
  return label?.type === "text" && typeof label.value === "string"
    && isSourceLink(label.value, link.properties.href);
}

export interface AttributedMarkdownQuoteHeader {
  readonly label: string;
  readonly permalink: string;
  readonly labelTextNode: object;
}

/** Locate source-authorship labels in mdast without treating normal links as metadata. */
export function collectAttributedMarkdownQuoteHeaders(tree: unknown): readonly AttributedMarkdownQuoteHeader[] {
  const headers: AttributedMarkdownQuoteHeader[] = [];
  function visit(value: unknown): void {
    const node = asNode(value);
    if (!node) return;
    if (node.type === "blockquote") {
      const paragraph = asNode(node.children?.[0]);
      if (paragraph?.type === "paragraph" && paragraph.children?.length === 1) {
        const link = asNode(paragraph.children[0]);
        const label = asNode(link?.children?.[0]);
        if (link?.type === "link" && typeof link.url === "string"
          && link.children?.length === 1 && label?.type === "text"
          && typeof label.value === "string"
          && isSourceLink(label.value, link.url)) {
          headers.push({ label: label.value, permalink: link.url, labelTextNode: label });
        }
      }
    }
    node.children?.forEach(visit);
  }
  visit(tree);
  return headers;
}
